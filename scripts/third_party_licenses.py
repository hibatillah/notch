"""Write THIRD-PARTY-LICENSES.txt: the license texts of every crate linked into notch.exe and notch-settings.exe."""

import json
import subprocess
import sys
from pathlib import Path

TARGET = "x86_64-pc-windows-msvc"
ROOT_PACKAGE_NAMES = {"notch", "notch-settings"}
LICENSE_FILE_PREFIXES = ("license", "licence", "copying", "unlicense", "notice")

repository_root = Path(__file__).resolve().parent.parent
metadata = json.loads(
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=repository_root, check=True, capture_output=True, encoding="utf-8",
    ).stdout
)
packages_by_id = {package["id"]: package for package in metadata["packages"]}
nodes_by_id = {node["id"]: node for node in metadata["resolve"]["nodes"]}

# Walk normal (non-dev, non-build) dependencies only; build and dev tools are not linked.
pending_ids = [pid for pid, package in packages_by_id.items() if package["name"] in ROOT_PACKAGE_NAMES]
linked_ids = set()
while pending_ids:
    package_id = pending_ids.pop()
    if package_id in linked_ids:
        continue
    linked_ids.add(package_id)
    for dependency in nodes_by_id[package_id]["deps"]:
        if any(kind["kind"] is None for kind in dependency["dep_kinds"]):
            pending_ids.append(dependency["pkg"])

texts_to_crates = {}
crates_without_text = []
for package_id in sorted(linked_ids, key=lambda pid: (packages_by_id[pid]["name"], packages_by_id[pid]["version"])):
    package = packages_by_id[package_id]
    if package["name"] in ROOT_PACKAGE_NAMES or package["name"] == "notch-store":
        continue
    crate_label = f'{package["name"]} {package["version"]}'
    crate_directory = Path(package["manifest_path"]).parent
    license_files = sorted(
        path for path in crate_directory.iterdir()
        if path.is_file() and path.name.lower().startswith(LICENSE_FILE_PREFIXES)
    )
    if not license_files:
        crates_without_text.append(f'{crate_label} (declared: {package["license"]})')
        continue
    for license_file in license_files:
        text = license_file.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
        texts_to_crates.setdefault(text, []).append(f'{crate_label} [{package["license"]}]')

lines = [
    "Third-party licenses",
    "",
    "Generated by scripts/third_party_licenses.sh from the crates linked into notch.exe and notch-settings.exe.",
    "Each text below is copied from the dependency sources and is followed by the crates it was found in.",
    "",
]
for text, crate_labels in sorted(texts_to_crates.items(), key=lambda item: item[1][0]):
    lines += ["=" * 78, "Used by:", *[f"  {label}" for label in sorted(set(crate_labels))], "-" * 78, text, ""]
if crates_without_text:
    lines += ["=" * 78, "Crates whose sources contain no license file (see their declared license):",
              *[f"  {label}" for label in crates_without_text], ""]

(repository_root / "THIRD-PARTY-LICENSES.txt").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{len(texts_to_crates)} distinct texts; {len(crates_without_text)} crates without a license file", file=sys.stderr)
for label in crates_without_text:
    print(f"  no license file: {label}", file=sys.stderr)
